/**
 * 拼音分词与候选词匹配器
 */
export class IMEEngine {
  constructor() {
    this.pinyinDict = IME_DATA.pinyinDict;
    this.phraseDict = IME_DATA.phraseDict;
    this.englishDict = IME_DATA.englishDict;
  }

  /**
   * 拼音候选词查询
   * @param {string} rawPinyin 拼音字符串 如 'nihao', 'zhong', 'shuru'
   * @returns {Array<string>} 候选字词列表
   */
  getCandidates(rawPinyin) {
    if (!rawPinyin) return [];
    const py = rawPinyin.toLowerCase().trim();

    // 1. 词组精准命中
    if (this.phraseDict[py]) {
      return [...this.phraseDict[py]];
    }

    // 2. 单字拼音精准命中
    if (this.pinyinDict[py]) {
      return [...this.pinyinDict[py]];
    }

    // 3. 前缀模糊匹配（查找以 py 开头的有效拼音词条）
    const matched = [];
    
    // 检查是否有前缀词组
    for (const [key, list] of Object.entries(this.phraseDict)) {
      if (key.startsWith(py)) {
        matched.push(...list);
      }
    }

    // 检查是否有前缀单字
    for (const [key, list] of Object.entries(this.pinyinDict)) {
      if (key.startsWith(py)) {
        matched.push(...list.slice(0, 3));
      }
    }

    // 4. 尝试贪婪双音节拆分 (例如 'ceshi' -> 'ce' + 'shi')
    if (matched.length === 0 && py.length > 2) {
      for (let i = 2; i <= Math.min(py.length, 6); i++) {
        const p1 = py.slice(0, i);
        const p2 = py.slice(i);
        if (this.pinyinDict[p1] && (this.pinyinDict[p2] || p2 === '')) {
          const w1 = this.pinyinDict[p1][0];
          const w2 = p2 ? (this.pinyinDict[p2] ? this.pinyinDict[p2][0] : '') : '';
          if (w1 + w2) {
            matched.push(w1 + w2);
          }
        }
      }
    }

    // 5. 兜底回退：返回大写拼音串及首字母拼写
    if (matched.length === 0) {
      matched.push(py);
    }

    // 去重
    return Array.from(new Set(matched));
  }

  /**
   * 9 键九宫格查询拼音候选与组合
   * @param {string} numberStr 数字串如 '64426'
   */
  get9KeyCandidates(numberStr) {
    if (!numberStr) return { pinyins: [], candidates: [] };
    
    // 映射预设
    const pinyins = IME_DATA.keypad9Combinations[numberStr] || [];
    if (pinyins.length > 0) {
      const candidates = [];
      pinyins.forEach(py => {
        candidates.push(...this.getCandidates(py));
      });
      return { pinyins, candidates: Array.from(new Set(candidates)) };
    }

    // 智能推测可能拼音组合（基于 9 键映射）
    const possibleLetters = numberStr.split('').map(d => IME_DATA.keypad9Map[d] || []);
    const combinations = [];

    // 递归生成前几个字母组合
    const generateCombos = (idx, current) => {
      if (combinations.length >= 6) return;
      if (idx === possibleLetters.length) {
        if (this.pinyinDict[current] || this.phraseDict[current]) {
          combinations.push(current);
        }
        return;
      }
      for (const char of possibleLetters[idx]) {
        generateCombos(idx + 1, current + char);
      }
    };

    generateCombos(0, '');
    const validPinyins = combinations.length > 0 ? combinations : [numberStr];
    const candList = [];
    validPinyins.forEach(py => {
      candList.push(...this.getCandidates(py));
    });

    return {
      pinyins: validPinyins,
      candidates: Array.from(new Set(candList))
    };
  }

  /**
   * 笔画输入法检索候选词
   */
  getStrokeCandidates(strokes) {
    if (!strokes) return [];
    if (IME_DATA.strokeDict && IME_DATA.strokeDict[strokes]) {
      return IME_DATA.strokeDict[strokes];
    }
    const first = strokes[0];
    if (IME_DATA.strokeMap[first]) {
      return IME_DATA.strokeMap[first].radicals;
    }
    return ['一', '二', '三', '十', '人', '木', '口', '日'];
  }

  /**
   * 英文单词补全联想
   */
  getEnglishCompletions(prefix) {
    if (!prefix) return [];
    const p = prefix.toLowerCase();
    if (this.englishDict[p]) {
      return this.englishDict[p];
    }
    return [prefix, prefix.toUpperCase(), prefix.charAt(0).toUpperCase() + prefix.slice(1)];
  }

  /**
   * 英文 T9 九键智能预测
   */
  getT9EnglishCandidates(digits) {
    if (!digits) return [];
    if (IME_DATA.t9EnglishDict && IME_DATA.t9EnglishDict[digits]) {
      return IME_DATA.t9EnglishDict[digits];
    }
    const matches = [];
    for (const word of Object.keys(this.englishDict)) {
      if (word.length === digits.length) {
        matches.push(word);
        if (matches.length >= 6) break;
      }
    }
    return matches.length > 0 ? matches : [digits];
  }
}
